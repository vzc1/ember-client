import java.lang.reflect.*;
import java.nio.file.*;
import java.util.*;

/**
 * Generates EmberLog4jLogger: an implementation of every method of
 * org.apache.logging.log4j.Logger that forwards to the game's own logger
 * (slf4j), so mods that log through Log4j work in the browser.
 * Usage: java -cp log4j-api.jar:. GenLog4jShim <out.java>
 */
public class GenLog4jShim {
	static String type(Type t) {
		if (t instanceof Class<?> c) {
			if (c.isArray()) return type(c.getComponentType()) + "[]";
			return c.getName().replace('$', '.');
		}
		if (t instanceof ParameterizedType p) return type(p.getRawType());
		if (t instanceof GenericArrayType g) return type(g.getGenericComponentType()) + "[]";
		if (t instanceof TypeVariable<?> v) return v.getName();
		return "Object";
	}

	public static void main(String[] a) throws Exception {
		Class<?> L = Class.forName("org.apache.logging.log4j.Logger");
		StringBuilder sb = new StringBuilder();
		sb.append("package org.apache.logging.log4j;\n\n// Generated by fabric/tools/log4j/GenLog4jShim.java. Do not edit.\n")
		  .append("@SuppressWarnings({\"unchecked\", \"rawtypes\", \"deprecation\"})\n")
		  .append("final class EmberLog4jLogger implements Logger {\n")
		  .append("\tprivate final String name;\n\tprivate final org.slf4j.Logger out;\n")
		  .append("\tEmberLog4jLogger(String name) { this.name = name; this.out = org.slf4j.LoggerFactory.getLogger(name); }\n")
		  .append("\tprivate static final Object[] NONE = new Object[0];\n")
		  .append("\tprivate void emit(String level, Object... args) { EmberLog4jSupport.emit(out, level, args); }\n")
		  .append("\tprivate boolean on(String level) { return EmberLog4jSupport.on(out, level); }\n\n");
		Set<String> seen = new HashSet<>();
		for (Method m : L.getMethods()) {
			if (Modifier.isStatic(m.getModifiers())) continue;
			String sig = m.getName() + Arrays.toString(m.getParameterTypes());
			if (!seen.add(sig)) continue;
			if (m.isDefault()) continue;
			StringBuilder head = new StringBuilder("\t@Override public ");
			TypeVariable<Method>[] tv = m.getTypeParameters();
			if (tv.length > 0) {
				head.append("<");
				for (int i = 0; i < tv.length; i++) {
					head.append(i > 0 ? ", " : "").append(tv[i].getName());
					Type[] bounds = tv[i].getBounds();
					if (bounds.length > 0 && !(bounds[0] == Object.class)) head.append(" extends ").append(type(bounds[0]));
				}
				head.append("> ");
			}
			Type rt = m.getGenericReturnType();
			head.append(type(rt)).append(' ').append(m.getName()).append('(');
			Type[] ps = m.getGenericParameterTypes();
			StringBuilder call = new StringBuilder();
			for (int i = 0; i < ps.length; i++) {
				String pt = type(ps[i]);
				if (m.isVarArgs() && i == ps.length - 1) pt = pt.substring(0, pt.length() - 2) + "...";
				head.append(i > 0 ? ", " : "").append(pt).append(" p").append(i);
				call.append(", p").append(i);
			}
			head.append(") { ");
			String n = m.getName();
			String lvl = switch (n) {
				case "trace", "debug", "info", "warn", "error", "fatal" -> n;
				case "log", "printf", "logMessage" -> "log";
				case "catching", "throwing" -> "error";
				case "entry", "exit", "traceEntry", "traceExit" -> "trace";
				default -> null;
			};
			Class<?> r = m.getReturnType();
			String body;
			if (n.startsWith("is") && n.endsWith("Enabled") && r == boolean.class) {
				String l = n.substring(2, n.length() - 7).toLowerCase(Locale.ROOT);
				body = l.isEmpty() ? "return true;" : "return on(\"" + l + "\");";
			} else if (n.equals("getName")) {
				body = "return name;";
			} else if (n.equals("getLevel")) {
				body = "return Level.INFO;";
			} else if (lvl != null) {
				body = "emit(\"" + lvl + "\"" + call + ");";
				if (r != void.class) {
					// traceExit(R)/throwing(T) return their argument; anything else returns null/false.
					String ret = "null";
					if (ps.length > 0 && type(rt).equals(type(ps[ps.length - 1]))) ret = "p" + (ps.length - 1);
					else if (r == boolean.class) ret = "false";
					else if (r.isPrimitive()) ret = "0";
					body += " return " + ret + ";";
				}
			} else if (r == void.class) {
				body = "";
			} else if (r == boolean.class) {
				body = "return false;";
			} else if (r.isPrimitive()) {
				body = "return 0;";
			} else if (r.getName().equals("org.apache.logging.log4j.LogBuilder")) {
				body = "return LogBuilder.NOOP;";
			} else {
				body = "return null;";
			}
			sb.append(head).append(body).append(" }\n");
		}
		sb.append("}\n");
		Files.writeString(Path.of(a[0]), sb.toString());
		System.out.println("GenLog4jShim: " + seen.size() + " methods");
	}
}
